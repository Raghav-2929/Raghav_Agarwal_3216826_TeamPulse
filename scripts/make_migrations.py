"""Generate (autogenerate) an Alembic revision for every service that owns a relational database.

    uv run python scripts/make_migrations.py "initial schema"

Each service keeps migrations inside its package (``src/<pkg>/migrations``) so the production image can
run ``python -m <pkg>.migrate`` as an ECS one-off task before a deployment.
"""

from __future__ import annotations

import shutil
import sys
import tempfile
from pathlib import Path

from teampulse_common import migrations

ROOT = Path(__file__).resolve().parents[1]
SERVICES = {
    "identity_service": ("identity-service", "identity_service.models"),
    "habit_service": ("habit-service", "habit_service.models"),
    "event_tracking_service": ("event-tracking-service", "event_tracking_service.models"),
    "challenge_service": ("challenge-service", "challenge_service.models"),
    "notification_service": ("notification-service", "notification_service.models"),
}
ENV_TEMPLATE = '''"""Alembic environment for {pkg} (generated by scripts/make_migrations.py)."""

from {models} import Base
from teampulse_common.db import MessagingBase
from teampulse_common.migrations import run_env

run_env([Base.metadata, MessagingBase.metadata])
'''


def main(message: str) -> None:
    for pkg, (service_dir, models) in SERVICES.items():
        location = ROOT / "services" / service_dir / "src" / pkg / "migrations"
        (location / "versions").mkdir(parents=True, exist_ok=True)
        (location / "env.py").write_text(ENV_TEMPLATE.format(pkg=pkg, models=models), encoding="utf-8")
        shutil.copy(migrations.TEMPLATE, location / "script.py.mako")
        with tempfile.TemporaryDirectory() as tmp:
            url = f"sqlite+aiosqlite:///{Path(tmp, 'schema.db').as_posix()}"
            migrations.upgrade(location, url)  # bring the scratch DB to head first
            migrations.revision(location, url, message)
        print(f"✓ {pkg}: {sorted(p.name for p in (location / 'versions').glob('*.py'))}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "schema change")
